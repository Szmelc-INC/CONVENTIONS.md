  fi
} | emit llms.txt

# --- CONVENTIONS.md (map of CONVENTIONS/ + all stable rules, one file) ---------
demote() { sed -E 's/^(#+) /#\1 /' "$1"; }
{
  echo '# {{profile.project_name}} Conventions (all-in-one)'
  echo "$GEN_NOTE"
  echo '> One-shot reference for tools that cannot lazy-load (aider `--read`, web chats, project knowledge). Agents with file access use `SKILL.md` + `INDEX.md` instead; never load this file alongside them. Stable rules only; the lazy-load instructions below do not apply here because every stable rule is inlined.'
  echo
  echo '## Map of `CONVENTIONS/`'
  map_body CONVENTIONS | sed 1,2d
  for f in AGENTS/global/AGENTS.md "${STABLE[@]}"; do
    echo
    echo '---'
    echo "<!-- source: $f -->"
    demote "$f"
  done
} | emit CONVENTIONS.md

# --- adapters (frontmatter-requiring tools) ----------------------------------
adapter() {
  local dest=$1 front=$2
  {
    printf -- '---\n%s\n---\n' "$front"
    echo "<!-- GENERATED by META/tools/build.sh from AGENTS/global/AGENTS.md. Do not edit. -->"
    cat AGENTS/global/AGENTS.md
  } | emit "$dest"
}
adapter AGENTS/adapters/cursor/szmelc-conventions.mdc $'description: {{profile.project_name}} global conventions (always on)\nalwaysApply: true'
adapter AGENTS/adapters/copilot/szmelc-conventions.instructions.md $'applyTo: "**"'
adapter AGENTS/adapters/kiro/szmelc-conventions.md $'inclusion: always'

# --- profile skill -----------------------------------------------------------
if ((profile_explicit)); then
  mkdir -p "$out/AGENTS/global" "$out/AGENTS/adapters"
  render < SKILL.md > "$out/SKILL.md"
  render < AGENTS/global/AGENTS.md > "$out/AGENTS/global/AGENTS.md"
fi

# --- check mode --------------------------------------------------------------
if ((check)); then
  stale=0
  if ((profile_explicit == 0)); then
    for f in "${GENERATED[@]}"; do
      if ! cmp -s "$out/$f" "$f"; then echo "stale: $f" >&2; stale=1; fi
    done
  fi
  ((stale == 0)) || { echo 'Run META/tools/build.sh' >&2; exit 1; }
  echo 'generated files up to date'
else
  echo "built: ${GENERATED[*]}"
fi
