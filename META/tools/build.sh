#!/usr/bin/env bash
# Generate indexes, core maps, the all-in-one bundle and tool adapters from source files.
# Usage: META/tools/build.sh [--check] [--profile NAME] [--team FILE] [--project FILE] [--user FILE] [--output DIR]
# Literal Markdown backticks in single quotes are intended.
# shellcheck disable=SC2016
set -euo pipefail
cd "$(dirname "$0")/../.."
export LC_ALL=C

GEN_NOTE='<!-- GENERATED by META/tools/build.sh from sources. Do not edit; edit the source and rebuild. -->'
# Core categories: each is a directory X/ with X/README.md, mapped by a root X.md.
CORES=(CONVENTIONS AGENTS HUMANS CONTRIBUTING META TEMPLATES)
MAPS=(HUMANS.md CONTRIBUTING.md META.md TEMPLATES.md) # fully generated maps; AGENTS.md and CONVENTIONS.md embed theirs
GENERATED=(
  INDEX.md index.json llms.txt CONVENTIONS.md AGENTS.md "${MAPS[@]}" COMPATIBILITY.md
  AGENTS/adapters/cursor/szmelc-conventions.mdc
  AGENTS/adapters/copilot/szmelc-conventions.instructions.md
  AGENTS/adapters/kiro/szmelc-conventions.md
)

check=0 profile=neutral profile_explicit=0 overlay_explicit=0 output_arg=''
team_file='' project_file='' user_file=''
while (($#)); do
  case $1 in
    --check) check=1 ;;
    --profile) profile=${2:?--profile needs a name}; profile_explicit=1; shift ;;
    --team) team_file=${2:?--team needs a file}; overlay_explicit=1; shift ;;
    --project) project_file=${2:?--project needs a file}; overlay_explicit=1; shift ;;
    --user) user_file=${2:?--user needs a file}; overlay_explicit=1; shift ;;
    --output) output_arg=${2:?--output needs a directory}; shift ;;
    -h|--help)
      echo 'Usage: META/tools/build.sh [--check] [--profile NAME] [--team FILE] [--project FILE] [--user FILE] [--output DIR]'
      exit 0
      ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

[[ $profile =~ ^[a-z0-9][a-z0-9-]*$ ]] || { echo "invalid profile name: $profile" >&2; exit 2; }
profile_file="PROFILES/$profile/profile.toml"
[[ -f PROFILES/neutral/profile.toml ]] || { echo 'base profile not found: PROFILES/neutral/profile.toml' >&2; exit 2; }
[[ -f $profile_file ]] || { echo "profile not found: $profile" >&2; exit 2; }
declare -A PROFILE_VALUES=()
declare -A DISABLED_IDS=()
load_profile() {
  local file=$1 key value
  while IFS=$'\t' read -r key value; do PROFILE_VALUES["$key"]=$value; done < <(awk '
    /^[[:space:]]*#/ { next }
    /^\[/{ section=$0; gsub(/^\[|\]$/, "", section); next }
    /^[[:space:]]*[A-Za-z0-9_.-]+[[:space:]]*=[[:space:]]*"/ {
      line=$0; sub(/^[[:space:]]*/, "", line); split(line, a, "="); key=a[1]; gsub(/[[:space:]]/, "", key)
      value=line; sub(/^[^=]*=[[:space:]]*"/, "", value); sub(/"[[:space:]]*$/, "", value)
      print section "." key "\t" value
    }
  ' "$file")
}

load_overrides() {
  local file=$1 kind key value
  [[ -f $file ]] || { echo "overlay not found: $file" >&2; exit 2; }
  while IFS=$'\t' read -r kind key value; do
    case $kind in
      D) [[ $key =~ ^[a-z0-9]+([.-][a-z0-9]+)*$ ]] || { echo "invalid disabled rule id in $file: $key" >&2; exit 2; }; DISABLED_IDS["$key"]=$file ;;
      S) [[ $key == profile.* ]] || { echo "overlay key must start with profile.: $key" >&2; exit 2; }; PROFILE_VALUES["$key"]=$value ;;
    esac
  done < <(awk '
    /^[[:space:]]*#/ { next }
    /^\[overrides\][[:space:]]*$/ { section="overrides"; next }
    /^\[overrides\.set\][[:space:]]*$/ { section="set"; next }
    /^\[/ { section=""; next }
    section == "overrides" && /^[[:space:]]*disable[[:space:]]*=/ {
      value=$0; sub(/^[^=]*=/, "", value)
      gsub(/\[/, "", value); gsub(/\]/, "", value); gsub(/"/, "", value); gsub(/[[:space:]]/, "", value)
      n=split(value, ids, ","); for (i=1; i<=n; i++) if (ids[i] != "") print "D\t" ids[i] "\t"
      next
    }
    section == "set" && /^[[:space:]]*[A-Za-z0-9_.-]+[[:space:]]*=[[:space:]]*"/ {
      line=$0; split(line, a, "="); key=a[1]; gsub(/[[:space:]]/, "", key)
      value=line; sub(/^[^=]*=[[:space:]]*"/, "", value); sub(/"[[:space:]]*$/, "", value)
      print "S\t" key "\t" value
    }
  ' "$file")
}

load_profile PROFILES/neutral/profile.toml
if [[ $profile != neutral ]]; then load_profile "$profile_file"; fi
load_overrides "$profile_file"
[[ -z $team_file ]] || load_overrides "$team_file"
[[ -z $project_file ]] || load_overrides "$project_file"
[[ -z $user_file ]] || load_overrides "$user_file"
profile_value() { [[ -n ${PROFILE_VALUES[$1]+x} ]] || { echo "profile $profile missing: $1" >&2; exit 2; }; printf '%s' "${PROFILE_VALUES[$1]}"; }
RAW="$(profile_value profile.raw_url)"

render() {
  local text key value escaped
  text=$(cat)
  for key in "${!PROFILE_VALUES[@]}"; do
    value=${PROFILE_VALUES[$key]}
    escaped=${value//\\/\\\\}; escaped=${escaped//&/\\&}; escaped=${escaped//|/\\|}
    text=$(printf '%s' "$text" | sed "s|{{${key}}}|$escaped|g")
  done
  printf '%s' "$text"
}

out=.
if [[ -n $output_arg ]]; then out=$output_arg
elif ((profile_explicit || overlay_explicit)); then out="PROFILES/$profile/rendered"
fi
if ((check)); then
  out=$(mktemp -d)
  trap 'rm -rf "$out"' EXIT
fi

# --- source discovery -------------------------------------------------------

# Markdown files inside the core directories (symlinks are not followed).
all_md() { find "${CORES[@]}" -type f -name '*.md' | sort; }

# status <path> → core | stable | experimental | legacy | skip
status() {
  case $1 in
    */*/*) ;;
    */README.md) echo core; return ;;
  esac
  case $1 in
    AGENTS/adapters/* | AGENTS/global/* | AGENTS/skills/* | TEMPLATES/* | META/tools/* | META/schema/* | META/compat/* | META/assets/*) echo skip ;;
    CONVENTIONS/EXPERIMENTAL/*) echo experimental ;;
    CONVENTIONS/LEGACY/*) echo legacy ;;
    *) echo stable ;;
  esac
}

files_with() {
  local f state id
  while IFS= read -r f; do
    state=$(status "$f")
    [[ $state == "$1" ]] || continue
    if [[ $state == stable || $state == experimental ]]; then
      id=$(fm "$f" id)
      [[ -z ${DISABLED_IDS[$id]:-} ]] || continue
    fi
    echo "$f"
  done < <(all_md)
}
title() { awk '/^# /{sub(/^# /, ""); print; exit}' "$1"; }
trigger() { awk '/^> Load when: /{sub(/^> Load when: /, ""); print; exit}' "$1"; }
# fm <file> <key> → top-level frontmatter value
fm() { awk -v k="$2" 'NR==1&&/^---$/{f=1;next} f&&/^---$/{exit} f&&index($0,k": ")==1{print substr($0,length(k)+3)}' "$1"; }
cell() { local s=$1; s=${s//|/\\|}; printf '%s' "$s"; }
json() { local s=$1; s=${s//\\/\\\\}; s=${s//\"/\\\"}; s=${s//$'\t'/\\t}; printf '"%s"' "$s"; }

# about <file> → one-line description of any file, for maps.
about() {
  local f=$1 t
  case $f in
    */SKILL.md) printf 'Skill `%s`' "$(fm "$f" name)" ;;
    *.md | *.mdc)
      t=$(grep -m1 '^# ' "$f" | sed 's/^# //')
      case $f in AGENTS/adapters/*) printf 'Generated adapter: %s' "$t" ;; *) printf '%s' "$t" ;; esac
      ;;
    *.json) jq -r '.title // .description // empty' "$f" 2>/dev/null || true ;;
    *) grep -m1 -E '^# [^!]' "$f" | sed 's/^# //' ;;
  esac
}

mapfile -t STABLE < <(files_with stable)
mapfile -t EXPERIMENTAL < <(files_with experimental)
mapfile -t LEGACY < <(files_with legacy)
mapfile -t SKILLS < <(find AGENTS/skills -mindepth 2 -maxdepth 2 -name SKILL.md | sort)
declare -A ALL_RULE_IDS=()
while IFS= read -r f; do
  state=$(status "$f")
  [[ $state == stable || $state == experimental ]] || continue
  id=$(fm "$f" id)
  [[ -z $id ]] || ALL_RULE_IDS["$id"]=$f
done < <(all_md)
for id in "${!DISABLED_IDS[@]}"; do
  [[ -n ${ALL_RULE_IDS[$id]:-} ]] || { echo "overlay disables unknown rule id: $id" >&2; exit 2; }
done

# origin <path> → third-party | original | "" (from the path: */THIRD-PARTY/*, */ORIGINAL/*)
origin() { case $1 in */THIRD-PARTY/*) echo third-party ;; */ORIGINAL/*) echo original ;; esac; }

# --- compatibility registry (META/compat/registry.toml, parsed by META/tools/compat.awk) ---
REGISTRY=META/compat/registry.toml
compat_raw=$(awk -f META/tools/compat.awk "$REGISTRY")
US=$'\037'
DISCLAIMER=''
COMPAT=()              # one US-separated record per entry, fields as in compat.awk
declare -A COMPAT_OF=() # rule path → space-separated registry ids that cite it in `spec`
while IFS= read -r line; do
  case ${line:0:1} in
    D) DISCLAIMER=${line#D"$US"} ;;
    E)
      COMPAT+=("${line#E"$US"}")
      IFS=$US read -r cid _ _ _ _ _ _ _ cspec _ <<<"${line#E"$US"}"
      for p in $cspec; do COMPAT_OF[$p]="${COMPAT_OF[$p]:+${COMPAT_OF[$p]} }$cid"; done
      ;;
  esac
done <<<"$compat_raw"

ALWAYS_TRIGGER='Installed as global instructions (CLAUDE.md, AGENTS.md, GEMINI.md, QWEN.md, …); always active'
COMPAT_TRIGGER='checking which third-party formats, specs, platforms, languages or tools these conventions are compatible with, and at which version.'
ENTRY_TRIGGER="Installed as skill \`$(profile_value profile.skill_name)\`; entry point and format map"

emit() { mkdir -p "$out/$(dirname "$1")"; render >"$out/$1"; }
link() { printf '[`%s`](%s)' "$1" "$1"; }

# --- core maps ----------------------------------------------------------------
# map_rows <core>: table of every tracked file under the core. CONVENTIONS lists
# stable rules only (experimental/legacy as directory rows) so lane PRs never touch it.
map_rows() {
  local core=$1 f
  echo '| Path | What | Load when |'
  echo '|---|---|---|'
  while IFS= read -r f; do
    case $f in
      "$core/README.md") continue ;;
      CONVENTIONS/EXPERIMENTAL/* | CONVENTIONS/LEGACY/* | META/compat/icons/*.svg | META/assets/screenshots/*.png) continue ;;
    esac
    echo "| $(link "$f") | $(cell "$(about "$f")") | $(cell "$(trigger "$f")") |"
  done < <(find "$core" \( -type f -o -type l \) | sort)
  if [[ $core == CONVENTIONS ]]; then
    echo "| $(link CONVENTIONS/EXPERIMENTAL/) | Opt-in proposals (lane \`experimental\`) | User opts into experimental conventions |"
    echo "| $(link CONVENTIONS/LEGACY/) | Superseded material, archived (lane \`legacy\`) | Asked about history |"
  fi
}

map_body() {
  local core=$1
  echo "> Load when: $(trigger "$core/README.md")"
  echo
  echo "Map of \`$core/\`. Full guide: $(link "$core/README.md")."
  echo
  map_rows "$core"
}

for m in "${MAPS[@]}"; do
  core=${m%.md}
  {
    echo "# $(title "$core/README.md")"
    echo "$GEN_NOTE"
    map_body "$core"
  } | emit "$m"
done

# AGENTS.md is hand-written (instructions for agents working on this repo) with a generated map block.
{
  awk '/^<!-- map:begin -->$/{exit} {print}' AGENTS.md
  echo '<!-- map:begin -->'
  echo '## Map of `AGENTS/`'
  echo "$GEN_NOTE"
  map_body AGENTS
  echo '<!-- map:end -->'
} | emit AGENTS.md

# --- INDEX.md ----------------------------------------------------------------
{
  echo '# Index'
  echo "$GEN_NOTE"
  echo 'Read this once per session. Load only files whose trigger matches the task. Paths are relative to the conventions repo.'
  echo
  echo '## Always on'
  echo '| File | Load when |'
  echo '|---|---|'
  echo "| \`AGENTS/global/AGENTS.md\` | $(cell "$ALWAYS_TRIGGER") |"
  echo "| \`SKILL.md\` | $(cell "$ENTRY_TRIGGER") |"
  echo
  echo '## Cores'
  echo '| File | Load when |'
  echo '|---|---|'
  for c in "${CORES[@]}"; do echo "| \`$c/README.md\` | $(cell "$(trigger "$c/README.md")") |"; done
  echo
  echo '## Compatibility'
  echo '| File | Load when |'
  echo '|---|---|'
  echo "| \`COMPATIBILITY.md\` | $(cell "$COMPAT_TRIGGER") |"
  echo
  echo '## Rules'
  echo '| File | Load when |'
  echo '|---|---|'
  for f in "${STABLE[@]}"; do echo "| \`$f\` | $(cell "$(trigger "$f")") |"; done
  echo
  echo '## Skills'
  echo '| File | Load when |'
  echo '|---|---|'
  for f in "${SKILLS[@]}"; do echo "| \`$f\` | $(cell "$(fm "$f" description)") |"; done
  echo
  echo '## Experimental (opt-in only)'
  if ((${#EXPERIMENTAL[@]})); then
    echo '| File | Load when |'
    echo '|---|---|'
    for f in "${EXPERIMENTAL[@]}"; do echo "| \`$f\` | $(cell "$(trigger "$f")") |"; done
  else
    echo '_None._'
  fi
  echo
  echo '## Legacy (archive; load only when asked)'
  if ((${#LEGACY[@]})); then
    echo '| File | Title |'
    echo '|---|---|'
    for f in "${LEGACY[@]}"; do echo "| \`$f\` | $(cell "$(title "$f")") |"; done
  else
    echo '_None._'
  fi
} | emit INDEX.md

# --- index.json --------------------------------------------------------------
{
  entries=()
  e() { # e <path> <title> <load_when> <status> <kind>; adds origin and compat (registry ids) when set
    local x o ids id rule_id
    x="    {\"path\": $(json "$1"), \"title\": $(json "$2"), \"load_when\": $(json "$3"), \"status\": $(json "$4"), \"kind\": $(json "$5")"
    if [[ $5 == rule ]]; then
      rule_id=$(fm "$1" id)
      [[ -n $rule_id ]] && x+=", \"id\": $(json "$rule_id")"
    fi
    o=$(origin "$1")
    [[ -n $o ]] && x+=", \"origin\": $(json "$o")"
    if [[ -n ${COMPAT_OF[$1]:-} ]]; then
      ids=''
      for id in ${COMPAT_OF[$1]}; do ids+="${ids:+, }$(json "$id")"; done
      x+=", \"compat\": [$ids]"
    fi
    entries+=("$x}")
  }
  compat=()
  for rec in "${COMPAT[@]}"; do
    IFS=$US read -r id name kind desc ver added updated icon spec home repo docs comm <<<"$rec"
    x="    {\"id\": $(json "$id"), \"name\": $(json "$name"), \"kind\": $(json "$kind"), \"description\": $(json "$desc"), \"version\": $(json "$ver"), \"added\": $(json "$added"), \"updated\": $(json "$updated")"
    [[ -n $icon ]] && x+=", \"icon\": $(json "$icon")"
    sp=''
    for p in $spec; do sp+="${sp:+, }$(json "$p")"; done
    lk=''
    for k in homepage repo docs community; do
      case $k in homepage) v=$home ;; repo) v=$repo ;; docs) v=$docs ;; community) v=$comm ;; esac
      [[ -n $v ]] && lk+="${lk:+, }\"$k\": $(json "$v")"
    done
    compat+=("$x, \"spec\": [$sp], \"links\": {$lk}}")
  done
  e AGENTS/global/AGENTS.md "$(title AGENTS/global/AGENTS.md)" "$ALWAYS_TRIGGER" always global
  e SKILL.md "$(fm SKILL.md name)" "$ENTRY_TRIGGER" always skill
  for c in "${CORES[@]}"; do e "$c/README.md" "$(title "$c/README.md")" "$(trigger "$c/README.md")" stable core; done
  for f in "${STABLE[@]}"; do e "$f" "$(title "$f")" "$(trigger "$f")" stable rule; done
  for f in "${SKILLS[@]}"; do e "$f" "$(fm "$f" name)" "$(fm "$f" description)" stable skill; done
  for f in "${EXPERIMENTAL[@]}"; do e "$f" "$(title "$f")" "$(trigger "$f")" experimental rule; done
  for f in "${LEGACY[@]}"; do e "$f" "$(title "$f")" "Only when asked about superseded conventions" legacy archive; done
  echo '{'
  echo '  "$schema": "META/schema/index.schema.json",'
  echo '  "name": "{{profile.skill_name}}",'
  echo '  "repo": "{{profile.repository_url}}",'
  echo '  "entries": ['
  last=$((${#entries[@]} - 1))
  for i in "${!entries[@]}"; do
    if ((i < last)); then echo "${entries[$i]},"; else echo "${entries[$i]}"; fi
  done
  echo '  ],'
  echo "  \"compatible_disclaimer\": $(json "$DISCLAIMER"),"
  echo '  "compatible": ['
  last=$((${#compat[@]} - 1))
  for i in "${!compat[@]}"; do
    if ((i < last)); then echo "${compat[$i]},"; else echo "${compat[$i]}"; fi
  done
  echo '  ]'
  echo '}'
} | emit index.json

# --- COMPATIBILITY.md (human table of the registry) --------------------------
{
  echo '# Compatible with'
  echo "$GEN_NOTE"
  echo "> Load when: $COMPAT_TRIGGER"
  echo
  echo "Third-party formats, specs, platforms, languages and tools these conventions are compatible with, at the listed version. Source: \`$REGISTRY\` (fields in its header); machine-readable in \`index.json\` (\`compatible\`). Rules about third-party formats live in \`CONVENTIONS/SPECS/THIRD-PARTY/\`."
  echo
  echo '| Name | Kind | Version | What | Rules | Links | Updated |'
  echo '|---|---|---|---|---|---|---|'
  for rec in "${COMPAT[@]}"; do
    IFS=$US read -r id name kind desc ver added updated icon spec home repo docs comm <<<"$rec"
    rules=''
    for p in $spec; do rules+="${rules:+, }\`$p\`"; done
    links=''
    for k in homepage repo docs community; do
      case $k in homepage) v=$home ;; repo) v=$repo ;; docs) v=$docs ;; community) v=$comm ;; esac
      [[ -n $v ]] && links+="${links:+ · }[$k](<$v>)"
    done
    echo "| $(cell "$name") | $kind | $(cell "$ver") | $(cell "$desc") | $rules | $links | $updated |"
  done
  echo
  echo "_Disclaimer:_ $DISCLAIMER"
} | emit COMPATIBILITY.md

