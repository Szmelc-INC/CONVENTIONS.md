// Package build contains Go implementations of individual build.sh stages.
package build

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedNote = "<!-- GENERATED by META/tools/build.sh from sources. Do not edit; edit the source and rebuild. -->"

var mapCores = []string{"HUMANS", "CONTRIBUTING", "META", "TEMPLATES"}

// CoreMaps renders the four fully generated core maps. The bundled and adapter
// outputs remain outside this Go slice until their renderers are ported.
func CoreMaps(root string) (map[string][]byte, error) {
	result := make(map[string][]byte, len(mapCores))
	for _, core := range mapCores {
		b, err := renderCoreMap(root, core)
		if err != nil {
			return nil, err
		}
		result[core+".md"] = b
	}
	return result, nil
}

func renderCoreMap(root, core string) ([]byte, error) {
	read := func(path string) (string, error) {
		b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		return string(b), err
	}
	readmePath := core + "/README.md"
	readme, err := read(readmePath)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", readmePath, err)
	}
	lines := strings.Split(readme, "\n")
	title := ""
	trigger := ""
	if len(lines) > 0 && strings.HasPrefix(lines[0], "# ") {
		title = strings.TrimPrefix(lines[0], "# ")
	}
	if len(lines) > 1 && strings.HasPrefix(lines[1], "> Load when: ") {
		trigger = strings.TrimPrefix(lines[1], "> Load when: ")
	}
	files := []string{}
	err = filepath.WalkDir(filepath.Join(root, core), func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if path == filepath.Join(root, core) {
			return nil
		}
		if d.IsDir() {
			return nil
		}
		rel, e := filepath.Rel(root, path)
		if e != nil {
			return e
		}
		files = append(files, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	var out strings.Builder
	fmt.Fprintf(&out, "# %s\n%s\n> Load when: %s\n\nMap of `%s/`. Full guide: [`%s`](%s).\n\n", title, generatedNote, trigger, core, readmePath, readmePath)
	out.WriteString("| Path | What | Load when |\n|---|---|---|\n")
	for _, path := range files {
		if path == readmePath || ignoredMapPath(path) {
			continue
		}
		text, e := read(path)
		if e != nil {
			return nil, fmt.Errorf("read %s: %w", path, e)
		}
		fmt.Fprintf(&out, "| [`%s`](%s) | %s | %s |\n", path, path, mapAbout(path, text), mapTrigger(text))
	}
	return finalNewline([]byte(out.String())), nil
}

// finalNewline returns text with exactly one trailing line feed. Every generated
// file ends that way, so the Go renderers match build.sh's render() byte for byte.
func finalNewline(text []byte) []byte {
	return append(bytes.TrimRight(text, "\n"), '\n')
}

func ignoredMapPath(path string) bool {
	return strings.HasPrefix(path, "META/compat/icons/") && strings.HasSuffix(path, ".svg") ||
		strings.HasPrefix(path, "META/assets/screenshots/") && strings.HasSuffix(path, ".png")
}

func mapAbout(path, text string) string {
	if strings.HasSuffix(path, ".json") {
		var metadata struct {
			Title       string `json:"title"`
			Description string `json:"description"`
		}
		if json.Unmarshal([]byte(text), &metadata) == nil {
			if metadata.Title != "" {
				return metadata.Title
			}
			return metadata.Description
		}
	}
	if strings.HasSuffix(path, "/SKILL.md") {
		return "Skill `" + frontmatter(text, "name") + "`"
	}
	title := firstHeading(text)
	if strings.HasPrefix(path, "AGENTS/adapters/") {
		return "Generated adapter: " + title
	}
	return title
}

func mapTrigger(text string) string {
	for _, line := range strings.Split(text, "\n") {
		if strings.HasPrefix(line, "> Load when: ") {
			return strings.TrimPrefix(line, "> Load when: ")
		}
	}
	return ""
}

func firstHeading(text string) string {
	for _, line := range strings.Split(text, "\n") {
		if strings.HasPrefix(line, "# ") {
			return strings.TrimPrefix(line, "# ")
		}
	}
	return ""
}

func frontmatter(text, key string) string {
	lines := strings.Split(text, "\n")
	if len(lines) == 0 || strings.TrimSpace(lines[0]) != "---" {
		return ""
	}
	for _, line := range lines[1:] {
		if strings.TrimSpace(line) == "---" {
			break
		}
		if strings.HasPrefix(line, key+": ") {
			return strings.Trim(strings.TrimPrefix(line, key+": "), "\"'")
		}
	}
	return ""
}
