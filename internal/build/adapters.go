package build

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

var adapterFrontmatter = []struct {
	path, frontmatter string
}{
	{"AGENTS/adapters/cursor/szmelc-conventions.mdc", "description: {{profile.project_name}} global conventions (always on)\nalwaysApply: true"},
	{"AGENTS/adapters/copilot/szmelc-conventions.instructions.md", "applyTo: \"**\""},
	{"AGENTS/adapters/kiro/szmelc-conventions.md", "inclusion: always"},
}

// AdapterOutputs renders the Cursor, Copilot, and Kiro global-rules adapters.
// An empty profile selects neutral; overlays apply in team, project, user order.
func AdapterOutputs(root string, opts IndexOptions) (map[string][]byte, error) {
	if opts.Profile == "" {
		opts.Profile = "neutral"
	}
	profile, _, err := indexProfile(root, opts.Profile, opts.Overlays)
	if err != nil {
		return nil, err
	}
	globalPath := "AGENTS/global/AGENTS.md"
	global, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(globalPath)))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", globalPath, err)
	}
	result := make(map[string][]byte, len(adapterFrontmatter))
	for _, adapter := range adapterFrontmatter {
		var out bytes.Buffer
		fmt.Fprintf(&out, "---\n%s\n---\n%s\n", adapter.frontmatter, generatedAdapterNote)
		out.Write(global)
		result[adapter.path] = finalNewline(renderProfile(out.Bytes(), profile))
	}
	return result, nil
}

const generatedAdapterNote = "<!-- GENERATED by META/tools/build.sh from AGENTS/global/AGENTS.md. Do not edit. -->"
