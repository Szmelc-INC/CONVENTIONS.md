package build

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

var adapterFrontmatter = []struct {
	tool, extension, frontmatter string
}{
	{"cursor", ".mdc", "description: {{profile.project_name}} global conventions (always on)\nalwaysApply: true"},
	{"copilot", ".instructions.md", "applyTo: \"**\""},
	{"kiro", ".md", "inclusion: always"},
}

// AdapterOutputs renders the Cursor, Copilot, and Kiro global-rules adapters.
// An empty profile selects the repository default (PROFILES/DEFAULT, else neutral);
// overlays apply in team, project, user order.
func AdapterOutputs(root string, opts IndexOptions) (map[string][]byte, error) {
	profile, _, err := indexProfile(root, opts.Profile, opts.Overlays)
	if err != nil {
		return nil, err
	}
	globalPath := "AGENTS/global/AGENTS.md"
	global, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(globalPath)))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", globalPath, err)
	}
	stem, err := adapterName(profile)
	if err != nil {
		return nil, err
	}
	result := make(map[string][]byte, len(adapterFrontmatter))
	for _, adapter := range adapterFrontmatter {
		var out bytes.Buffer
		fmt.Fprintf(&out, "---\n%s\n---\n%s\n", adapter.frontmatter, generatedAdapterNote)
		out.Write(global)
		result["AGENTS/adapters/"+adapter.tool+"/"+stem+adapter.extension] = finalNewline(renderProfile(out.Bytes(), profile))
	}
	return result, nil
}

// adapterName is the file stem of the adapters: profile.adapter_name, or the
// skill name when the profile does not set one.
func adapterName(profile map[string]string) (string, error) {
	stem := profile["profile.adapter_name"]
	if stem == "" {
		stem = profile["profile.skill_name"]
	}
	if !validProfileName(stem) {
		return "", fmt.Errorf("invalid adapter name: %q", stem)
	}
	return stem, nil
}

const generatedAdapterNote = "<!-- GENERATED by META/tools/build.sh from AGENTS/global/AGENTS.md. Do not edit. -->"
